/**
 * 法規／標準回答護欄（system prompt 片段）。
 *
 * 背景（2026-08 A/B 實測）：三顆候選模型在被問到建築／工程／消防法規時，
 * 都出現同一組錯誤：
 *   1. 引用中國 GB 國家標準，並以「我國規定」稱之
 *   2. 生出**不存在**的法規編號（看起來合理、查無此法）
 *   3. 把外國標準（GB／ISO／NFPA）與台灣法規混為一談
 *
 * 這在災防場景是會出事的：現場人員可能照著一條不存在的「法規」做結構安全判斷。
 * 模型的訓練語料以簡體中文為大宗，這是語料偏差造成的系統性行為，
 * 不是個別提問的運氣問題，因此護欄放在 system prompt，對所有此類路徑一律生效。
 *
 * 這一版是**純 prompt 護欄**，只能降低錯誤率，無法根除幻覺。
 * 後續應接上可檢索的台灣法規知識庫（ST 專案的 regulation-rag 或自建 RAG），
 * 讓回答 ground 在真實條文上——屆時本檔的措辭改為「僅能引用檢索結果中的條文」。
 */

export const REGULATORY_GUARDRAIL_ZH_TW = `【法規與標準的回答規則｜必須嚴格遵守】
1. 不得引用任何「沒有出現在本次提供資料中」的法條、標準編號、條號或年份。
   你的記憶不算來源。想不起確切出處時，就說明「無法確認具體條號」，不要生成看起來合理的編號。
2. 本平台服務對象在台灣。中國大陸的 GB／GB/T 國家標準、以及 ISO／NFPA／ASTM 等國際或外國標準，
   **一律不得**稱為「我國規定」「國家標準」「法規要求」。若確實要提及，必須明確標示是哪一國／哪個組織的標準，
   並說明其在台灣不具法規效力。
3. 涉及台灣法規時，只講你能確定的原則性內容（例如「建築物公共安全檢查有定期申報制度」），
   並請使用者以主管機關的最新公告為準（內政部國土管理署、內政部消防署、勞動部職安署、
   全國法規資料庫 law.moj.gov.tw）。
4. 不確定就直說不確定。在災防場景中，一句「我不確定，請查證」遠優於一個看似專業但錯誤的條號。
5. 涉及結構安全、危險物品、醫療處置等可能致人傷亡的判斷，一律附上「請由具資格的專業人員現場確認」。`;

/**
 * 把護欄接在既有 system prompt 之後。
 *
 * 放在後面而不是前面，是為了讓各服務原本的角色設定（語氣、任務）先建立，
 * 護欄作為不可違背的附加約束收尾——實測較不容易被後續對話稀釋。
 */
export function withRegulatoryGuardrail(systemPrompt?: string): string {
    return [systemPrompt?.trim(), REGULATORY_GUARDRAIL_ZH_TW].filter(Boolean).join('\n\n');
}
